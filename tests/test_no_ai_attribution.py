import tempfile
import unittest
from pathlib import Path

from hookrun import bash_event, decision, run_hook


def check(event):
    return run_hook("no-ai-attribution", "check_attribution.py", event)


class BashCommandTest(unittest.TestCase):
    def test_commit_with_co_author_trailer_is_denied(self):
        cmd = ('git commit -m "$(cat <<\'EOF\'\nfix: x\n\n'
               'Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\nEOF\n)"')
        result = check(bash_event(cmd))
        self.assertEqual(decision(result), "deny")
        self.assertIn("Co-Authored-By", result["json"]["hookSpecificOutput"]["permissionDecisionReason"])

    def test_pr_body_with_generated_line_is_denied(self):
        cmd = 'gh pr create --title t --body "Fix\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"'
        self.assertEqual(decision(check(bash_event(cmd))), "deny")

    def test_gitlab_note_via_curl_is_denied(self):
        cmd = ('curl -X POST -H "PRIVATE-TOKEN: $T" '
               '--data-urlencode "body=Looks good. Generated with Claude Code" https://gitlab.example/api/v4/x')
        self.assertEqual(decision(check(bash_event(cmd))), "deny")

    def test_git_with_global_options_is_still_recognised(self):
        cmd = 'git -C repo -c core.editor=true commit -m "x\n\nCo-authored-by: claude <noreply@anthropic.com>"'
        self.assertEqual(decision(check(bash_event(cmd))), "deny")

    def test_message_file_is_read(self):
        with tempfile.TemporaryDirectory() as d:
            Path(d, "msg.txt").write_text("feat: y\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n")
            self.assertEqual(decision(check(bash_event("git commit -F msg.txt", cwd=d))), "deny")
            Path(d, "body.md").write_text("Summary\n\nGenerated with Claude Code\n")
            self.assertEqual(decision(check(bash_event("gh pr create --body-file body.md", cwd=d))), "deny")
            Path(d, "note.json").write_text('{"body": "ok. Generated by Claude"}')
            self.assertEqual(decision(check(bash_event("curl -d @note.json https://x", cwd=d))), "deny")

    def test_clean_commit_passes(self):
        result = check(bash_event('git commit -m "feat: [ABC-1] add parser"'))
        self.assertIsNone(result["json"])
        self.assertEqual(result["code"], 0)

    def test_reading_commands_are_not_checked(self):
        # Searching history for the trailer is not publishing it.
        for cmd in ('git log --grep "Co-Authored-By: Claude"',
                    'grep -rn "noreply@anthropic.com" .'):
            with self.subTest(cmd=cmd):
                self.assertIsNone(check(bash_event(cmd))["json"])

    def test_mentioning_claude_without_attribution_passes(self):
        cmd = 'git commit -m "docs: explain how Claude Code hooks are configured"'
        self.assertIsNone(check(bash_event(cmd))["json"])


class McpToolTest(unittest.TestCase):
    def test_mcp_pr_creation_is_checked(self):
        event = {"tool_name": "mcp__github__create_pull_request",
                 "tool_input": {"title": "t", "body": "Co-Authored-By: Claude <noreply@anthropic.com>"}}
        self.assertEqual(decision(check(event)), "deny")

    def test_mcp_read_tools_are_ignored(self):
        event = {"tool_name": "mcp__github__get_pull_request",
                 "tool_input": {"body": "Co-Authored-By: Claude"}}
        self.assertIsNone(check(event)["json"])


class RobustnessTest(unittest.TestCase):
    def test_broken_input_never_blocks(self):
        result = run_hook("no-ai-attribution", "check_attribution.py", {"tool_name": "Bash"})
        self.assertEqual(result["code"], 0)

    def test_unbalanced_quotes_still_checked(self):
        cmd = 'git commit -m "x\n\nCo-Authored-By: Claude <noreply@anthropic.com>'
        self.assertEqual(decision(check(bash_event(cmd))), "deny")


if __name__ == "__main__":
    unittest.main()
